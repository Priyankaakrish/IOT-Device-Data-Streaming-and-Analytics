SET search_path TO mart, public;

-- ---------------------------------------------------------------------
-- 1. Security dimension -- single source of truth for who sees what.
--    Consumed by BOTH Postgres RLS and Power BI dynamic RLS.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dim_user_scope (
    user_scope_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_principal_name  VARCHAR(200) NOT NULL,     -- matches Entra ID UPN / USERPRINCIPALNAME()
    plant_code           VARCHAR(20),               -- NULL = all plants
    production_line      VARCHAR(50),               -- NULL = all lines in that plant
    role_name            VARCHAR(50)  NOT NULL,
    is_active            BOOLEAN      NOT NULL DEFAULT TRUE,
    granted_by           VARCHAR(200),
    granted_at           TIMESTAMP    NOT NULL DEFAULT NOW(),
    review_due           DATE,
    CONSTRAINT chk_scope_role CHECK (
        role_name IN ('EXECUTIVE','PLANT_MANAGER','LINE_SUPERVISOR','MAINTENANCE_TECH','AUDITOR')
    )
);
CREATE INDEX IF NOT EXISTS ix_user_scope_upn
    ON dim_user_scope (LOWER(user_principal_name)) WHERE is_active;

COMMENT ON TABLE dim_user_scope IS
    'Access matrix. NULL plant_code = global. NULL production_line = whole plant.';

