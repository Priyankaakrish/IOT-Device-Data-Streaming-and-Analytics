-- IoT Device Data Streamlining -- Row-Level Security (PostgreSQL)
-- =====================================================================
-- Defence in depth. Power BI RLS protects the report; this protects the
-- database if anyone connects directly with psql, DBeaver or Excel.
-- A security model that exists only in the BI tool is not a security model.
