-- ---------------------------------------------------------------------
-- Staging table for the streaming job's hourly upsert.
--
-- Defined explicitly rather than with (LIKE fact_production_hourly).
-- LIKE copies NOT NULL constraints but NOT the identity generator or
-- column defaults, so production_hour_id / alert_count / created_at all
-- arrive NULL from Spark and the batch insert is rejected with:
--   ERROR: null value in column "production_hour_id" violates not-null
--
-- Columns here are exactly what Spark writes, all nullable.
-- UNLOGGED because the contents are transient: they are merged into the
-- fact within the same batch and never need crash recovery.
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS stg_production_hourly;
CREATE UNLOGGED TABLE stg_production_hourly (
    date_key            INTEGER,
    time_key            SMALLINT,
    machine_key         BIGINT,
    shift_key           SMALLINT,
    window_start        TIMESTAMP,
    window_end          TIMESTAMP,
    reading_count       BIGINT,
    units_produced      BIGINT,
    good_units          BIGINT,
    scrap_units         BIGINT,
    runtime_minutes     DOUBLE PRECISION,
    idle_minutes        DOUBLE PRECISION,
    downtime_minutes    DOUBLE PRECISION,
    planned_minutes     DOUBLE PRECISION,
    energy_kwh          DOUBLE PRECISION,
    avg_temperature_c   DOUBLE PRECISION,
    max_temperature_c   DOUBLE PRECISION,
    temp_sum            DOUBLE PRECISION,
    avg_vibration_mm_s  DOUBLE PRECISION,
    max_vibration_mm_s  DOUBLE PRECISION
);

-- =====================================================================
-- SECTION 4 -- RESERVED "UNKNOWN" MEMBERS
--
-- Never allow NULL foreign keys. Inner joins silently drop them, which
-- converts a data-quality problem into silent under-reporting -- the
-- worst failure mode in analytics.
-- =====================================================================

INSERT INTO dim_shift (shift_key, shift_code, shift_name, start_time, end_time, planned_minutes)
VALUES (-1, 'UNK', 'Unknown', '00:00', '00:00', 0)
ON CONFLICT (shift_key) DO NOTHING;

INSERT INTO dim_machine_status
    (status_key, status_code, status_name, status_category, is_productive,
     is_downtime, is_planned_downtime, counts_toward_oee, display_colour_hex, sort_order)
VALUES (-1, 'UNKNOWN', 'Unknown', 'UNKNOWN', FALSE, FALSE, FALSE, FALSE, '#9E9E9E', 99)
ON CONFLICT (status_key) DO NOTHING;

INSERT INTO dim_reading_flags (flags_key, is_outlier, is_backfilled, is_estimated, flag_description)
VALUES (1, FALSE, FALSE, FALSE, 'Clean reading')
ON CONFLICT (flags_key) DO NOTHING;

-- =====================================================================
-- SECTION 5 -- FOREIGN KEYS ON THE PARTITIONED FACT
--
-- NOTE: PostgreSQL supports foreign keys FROM a partitioned table, but
-- NOT the NOT VALID modifier on them:
--   ERROR: cannot add NOT VALID foreign key on partitioned table
--          DETAIL: This feature is not yet supported on partitioned tables.
--
-- So these are created fully validated. That is cheap here because the
-- fact is empty at this point in the deployment order (04 runs before
-- the 06 backfill). If you ever re-add these to a populated table,
-- expect a full scan and schedule it off-peak.
-- =====================================================================

ALTER TABLE fact_sensor_reading
    DROP CONSTRAINT IF EXISTS fk_fsr_machine;
ALTER TABLE fact_sensor_reading
    ADD CONSTRAINT fk_fsr_machine FOREIGN KEY (machine_key)
    REFERENCES dim_machine(machine_key);

ALTER TABLE fact_sensor_reading
    DROP CONSTRAINT IF EXISTS fk_fsr_status;
ALTER TABLE fact_sensor_reading
    ADD CONSTRAINT fk_fsr_status FOREIGN KEY (status_key)
    REFERENCES dim_machine_status(status_key);
