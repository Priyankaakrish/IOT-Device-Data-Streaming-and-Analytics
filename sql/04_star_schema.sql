CREATE TABLE IF NOT EXISTS dq_exception (
    exception_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    detected_at        TIMESTAMP    NOT NULL DEFAULT NOW(),
